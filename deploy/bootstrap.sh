#!/usr/bin/env bash
# bootstrap.sh — create deploy/.env from the kernel's and this repository's
# examples, with fresh secrets.
#
# One .env serves both Compose files: this directory's compose.yml and the
# kernel's (kernel/deploy/compose.yml), which compose.yml includes with this
# .env. The kernel's example comes first and this repository's second, so a
# solver-side value overrides a kernel default of the same name.
#
# Idempotent: an existing .env is left alone unless --force is given.
# Regenerating SOLVER_AUTH_TOKEN under a running stack would break the solver's
# WebSocket upgrade (the relay would answer 401) while everything still looked
# healthy, and regenerating INDEXER_SECRET under an existing indexer volume
# leaves the wallet data it encrypted unreadable.
set -euo pipefail

cd "$(dirname "$0")"

FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1

if [ -f .env ] && [ "${FORCE}" -eq 0 ]; then
  echo "deploy/.env already exists — leaving it alone (pass --force to regenerate)."
  exit 0
fi

KERNEL_EXAMPLE=../kernel/deploy/.env.example
if [ ! -f "${KERNEL_EXAMPLE}" ]; then
  echo "${KERNEL_EXAMPLE} is missing — run: git submodule update --init" >&2
  exit 1
fi
command -v openssl >/dev/null 2>&1 || { echo "openssl is required" >&2; exit 1; }

# 64 hex characters: over the 32-character minimum both the relay and the
# solver enforce on these bearers.
SOLVER_AUTH_TOKEN="$(openssl rand -hex 32)"
SOLVER_STATUS_AUTH_TOKEN="$(openssl rand -hex 32)"
# The indexer wants uppercase hex for APP__INFRA__SECRET.
INDEXER_SECRET="$(openssl rand -hex 32 | tr 'a-f' 'A-F')"

umask 077
tmp="$(mktemp)"
{
  echo "# Generated by deploy/bootstrap.sh from ${KERNEL_EXAMPLE} and deploy/.env.example."
  echo
  cat "${KERNEL_EXAMPLE}"
  echo
  cat .env.example
} | sed -e "s|^SOLVER_AUTH_TOKEN=.*|SOLVER_AUTH_TOKEN=${SOLVER_AUTH_TOKEN}|" \
        -e "s|^SOLVER_STATUS_AUTH_TOKEN=.*|SOLVER_STATUS_AUTH_TOKEN=${SOLVER_STATUS_AUTH_TOKEN}|" \
        -e "s|^INDEXER_SECRET=.*|INDEXER_SECRET=${INDEXER_SECRET}|" > "${tmp}"
mv "${tmp}" .env
chmod 600 .env

echo "Wrote deploy/.env (gitignored) with generated SOLVER_AUTH_TOKEN, SOLVER_STATUS_AUTH_TOKEN and INDEXER_SECRET."
echo "Review the host ports before starting — this is a shared machine:"
grep -E '^(COMPOSE_PROJECT_NAME|BIND_ADDR|HOST_)' .env
